use std::path::{Path, PathBuf};

use clap::{CommandFactory, Parser, ValueEnum};

/// A backend the harness can build and run. Rust is always the reference
/// that the other targets are compared against.
#[derive(Clone, Copy, Debug, PartialEq, Eq, ValueEnum)]
pub enum Target {
    Rust,
    Cuda,
    Java,
}

impl Target {
    pub fn name(self) -> &'static str {
        match self {
            Target::Rust => "rust",
            Target::Cuda => "cuda",
            Target::Java => "java",
        }
    }
}

/// Differential harness for the generated Rust, CUDA and Java worldgen
/// pipelines. Rust is the reference; the other selected targets are compared
/// against it.
///
/// Every option can also be set via the matching environment variable; CLI
/// flags take precedence.
#[derive(Parser, Debug)]
#[command(author, version, about, long_about = None)]
pub struct Cli {
    /// Datapack source folder to compile into `generated-dir` before
    /// running the diff (phase 0). Phase 0 always runs: without this flag
    /// only the bundled vanilla worldgen is compiled.
    #[arg(long, env = "TUNGSTEN_SOURCE_DIR")]
    pub source_dir: Option<PathBuf>,

    /// Directory receiving the generated sources: `density.rs`,
    /// `GeneratedWorldgen.java`, `density_function.cu`, `orchestration.cu`.
    /// (`helpers.cu` must be supplied separately.)
    #[arg(long, env = "TUNGSTEN_GENERATED_DIR")]
    pub generated_dir: Option<PathBuf>,

    /// Directory the harness writes build artifacts (shared libs, Java classes) to.
    #[arg(long, env = "TUNGSTEN_DIFF_BUILD_DIR")]
    pub build_dir: Option<PathBuf>,

    /// Chunk size used when compiling from `--source-dir`.
    #[arg(long, env = "TUNGSTEN_DIFF_CHUNK_SIZE", default_value_t = 16)]
    pub chunk_size: usize,

    /// Perform a single compile/build/run/compare pass over `--source-dir`
    /// (or the existing `generated-dir`) and report the result, skipping
    /// the automatic shrink-on-mismatch search.
    #[arg(long, short = 's', env = "TUNGSTEN_DIFF_SINGLE_RUN")]
    pub single_run: bool,

    /// Targets to build and run, comma separated. `rust` is required because
    /// it is the reference the others are compared against. CUDA can't be
    /// generated by the compiler right now, so it isn't a default.
    #[arg(
        long,
        env = "TUNGSTEN_DIFF_TARGETS",
        value_enum,
        value_delimiter = ',',
        default_values_t = [Target::Rust, Target::Java]
    )]
    pub targets: Vec<Target>,

    /// Directory with the Java `tungsten.runtime` sources, compiled together
    /// with the generated code. Defaults to `java_wrapper/runtime/` in the
    /// harness crate.
    #[arg(long, env = "TUNGSTEN_JAVA_RUNTIME_DIR")]
    pub java_runtime_dir: Option<PathBuf>,

    /// World seed fed to all pipelines.
    #[arg(long, env = "TUNGSTEN_DIFF_SEED", default_value_t = 0)]
    pub seed: i64,

    /// Chunk-local origin X fed to all pipelines.
    #[arg(long, env = "TUNGSTEN_DIFF_ORIGIN_X", default_value_t = 0.0)]
    pub origin_x: f64,

    /// Chunk-local origin Y fed to all pipelines.
    #[arg(long, env = "TUNGSTEN_DIFF_ORIGIN_Y", default_value_t = -64.0)]
    pub origin_y: f64,

    /// Chunk-local origin Z fed to all pipelines.
    #[arg(long, env = "TUNGSTEN_DIFF_ORIGIN_Z", default_value_t = 0.0)]
    pub origin_z: f64,

    /// Absolute/relative tolerance for the CUDA comparison.
    #[arg(long, env = "TUNGSTEN_DIFF_EPSILON", default_value_t = 1e-6)]
    pub epsilon: f64,

    /// Tolerance for the Java comparison. The default 0 means bitwise
    /// equality, which is the accuracy target (any two NaNs count as equal).
    /// A non-zero value is only an escape hatch while triaging mismatches. It
    /// is NOT the accuracy target.
    #[arg(long, env = "TUNGSTEN_DIFF_JAVA_EPSILON", default_value_t = 0.0)]
    pub java_epsilon: f64,
}

/// All paths and knobs the harness needs, resolved from the CLI (which in
/// turn falls back to environment variables and defaults).
pub struct HarnessConfig {
    /// Directory containing `density.rs`, `density_function.cu`,
    /// `orchestration.cu`, and `helpers.cu` for a single compiled pipeline.
    pub generated_dir: PathBuf,
    /// Directory the harness writes build artifacts (the two .so files) to.
    pub build_dir: PathBuf,
    /// Path to the tungsten-diff-rust-wrapper crate.
    pub rust_wrapper_manifest: PathBuf,
    /// Path to the CUDA wrapper source.
    pub cuda_wrapper_src: PathBuf,
    /// Targets to build and run. Always contains `Target::Rust`.
    pub targets: Vec<Target>,
    /// Directory with the Java runtime sources (`tungsten.runtime`).
    pub java_runtime_dir: PathBuf,
    /// The Java driver that runs the generated code and dumps the result.
    pub java_driver_source: PathBuf,
    /// World seed fed to all pipelines.
    pub seed: i64,
    /// Chunk-local origin fed to all pipelines.
    pub origin: (f64, f64, f64),
    /// Tolerance for the CUDA comparison.
    pub epsilon: f64,
    /// Tolerance for the Java comparison; 0 means bitwise.
    pub java_epsilon: f64,
}

impl HarnessConfig {
    pub fn from_cli(cli: &Cli) -> Self {
        if !cli.targets.contains(&Target::Rust) {
            Cli::command()
                .error(
                    clap::error::ErrorKind::ValueValidation,
                    "--targets must include `rust`: it is the reference the other targets are compared against",
                )
                .exit();
        }
        let mut targets = cli.targets.clone();
        targets.dedup();

        let manifest_dir = PathBuf::from(env!("CARGO_MANIFEST_DIR"));

        let generated_dir = cli
            .generated_dir
            .clone()
            .unwrap_or_else(|| manifest_dir.join("generated"));

        let build_dir = cli
            .build_dir
            .clone()
            .unwrap_or_else(|| manifest_dir.join("target").join("diff-harness"));

        Self {
            generated_dir,
            build_dir,
            rust_wrapper_manifest: manifest_dir.join("rust_wrapper").join("Cargo.toml"),
            cuda_wrapper_src: manifest_dir.join("cuda_wrapper"),
            targets,
            java_runtime_dir: cli
                .java_runtime_dir
                .clone()
                .unwrap_or_else(|| manifest_dir.join("java_wrapper").join("runtime")),
            java_driver_source: manifest_dir
                .join("java_wrapper")
                .join("driver")
                .join("tungsten")
                .join("harness")
                .join("HarnessMain.java"),
            seed: cli.seed,
            origin: (cli.origin_x, cli.origin_y, cli.origin_z),
            epsilon: cli.epsilon,
            java_epsilon: cli.java_epsilon,
        }
    }

    pub fn has_target(&self, target: Target) -> bool {
        self.targets.contains(&target)
    }

    pub fn density_rs(&self) -> PathBuf {
        self.generated_dir.join("density.rs")
    }

    pub fn rust_cdylib_path(&self) -> PathBuf {
        // cdylib naming matches the Cargo package name declared in
        // rust_wrapper/Cargo.toml.
        cdylib_path(&self.build_dir.join("rust"), "tungsten_diff_rust_wrapper")
    }

    pub fn java_source(&self) -> PathBuf {
        self.generated_dir.join("GeneratedWorldgen.java")
    }

    pub fn java_classes_dir(&self) -> PathBuf {
        self.build_dir.join("java").join("classes")
    }

    pub fn java_output_path(&self) -> PathBuf {
        self.build_dir.join("java").join("output.bin")
    }

    pub fn cuda_shared_lib_path(&self) -> PathBuf {
        self.build_dir.join("cuda").join("libcuda_pipeline.so")
    }
}

/// Resolves the platform-specific cdylib filename cargo would produce for
/// `crate_name` inside `target_dir` (e.g. `target_dir/release/libfoo.so`).
fn cdylib_path(target_dir: &Path, crate_name: &str) -> PathBuf {
    let file_name = if cfg!(target_os = "windows") {
        format!("{crate_name}.dll")
    } else if cfg!(target_os = "macos") {
        format!("lib{crate_name}.dylib")
    } else {
        format!("lib{crate_name}.so")
    };
    target_dir.join("release").join(file_name)
}
